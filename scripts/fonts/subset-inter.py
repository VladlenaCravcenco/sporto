"""Generate local Unicode subsets; requires fonttools + brotli only for this script."""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools import subset
from fontTools.varLib.instancer import instantiateVariableFont

root = Path(__file__).resolve().parents[2]
folder = root / 'public/fonts/inter'
source = folder / 'InterVariable.woff2'
# Non-overlapping CSS ranges: shared digits/punctuation belong to Latin.
all_ranges = [(0x20, 0x24F), (0x300, 0x36F), (0x400, 0x52F),
              (0x2000, 0x206F), (0x20A0, 0x20CF), (0x2100, 0x214F),
              (0x2190, 0x21FF), (0x2200, 0x22FF), (0xFEFF, 0xFEFF), (0xFFFD, 0xFFFD)]
sets = {
    'Latin': [(0x20, 0xFF), (0x102, 0x103), (0x15E, 0x15F), (0x162, 0x163),
              (0x218, 0x21B), (0x300, 0x36F), (0x2000, 0x206F), (0x20A0, 0x20CF)],
    'Cyrillic': [(0x400, 0x52F)],
}
# Rare Latin letters, math and arrows are available without downloading them
# on every ordinary RO/RU page.
covered = {n for ranges in sets.values() for a, b in ranges for n in range(a, b + 1)}
remaining = sorted({n for a, b in all_ranges for n in range(a, b + 1)} - covered)
extra = []
for point in remaining:
    if extra and point == extra[-1][1] + 1:
        extra[-1] = (extra[-1][0], point)
    else:
        extra.append((point, point))
sets['Extras'] = extra
css = ['/* Generated by scripts/fonts/subset-inter.py. SIL OFL: public/fonts/inter/LICENSE.txt. */']
coverage = set()
for name, ranges in sets.items():
    font = TTFont(source)
    original = font.getBestCmap()
    codepoints = {n for start, end in ranges for n in range(start, end + 1)}
    assert not coverage.intersection(codepoints)
    options = subset.Options()
    options.flavor = 'woff2'
    # Keep browser shaping and the tabular numerals used by prices/counters.
    # Unused stylistic alternates remain available in the original source font.
    options.layout_features = ['calt', 'ccmp', 'kern', 'locl', 'mark', 'mkmk',
                               'tnum', 'liga', 'clig', 'rlig', 'rvrn']
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    font = instantiateVariableFont(font, {'opsz': 14}, inplace=True)
    font.flavor = 'woff2'
    target = folder / f'Inter{name}Core.woff2'
    font.save(target)
    result = TTFont(target)
    assert (set(original) & codepoints) <= set(result.getBestCmap())
    assert [(a.axisTag, a.minValue, a.maxValue) for a in result['fvar'].axes] == [('wght', 100, 900)]
    coverage.update(set(result.getBestCmap()) & codepoints)
    unicode_range = ', '.join(f'U+{a:04X}-{b:04X}' if a != b else f'U+{a:04X}' for a, b in ranges)
    css.append(f'''@font-face {{
  font-family: 'Inter';
  src: url('/fonts/inter/Inter{name}Core.woff2') format('woff2');
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  unicode-range: {unicode_range};
}}''')
    print(f'{name}: {target.stat().st_size} bytes')
required = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyzĂăÂâÎîȘșȚțŞşŢţ' + ''.join(chr(n) for n in range(0x410, 0x450)) + 'Ёё0123456789€₽°×–—'
assert all(ord(c) in coverage for c in required)
css.append('''body {
  font-family: 'Inter', -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}''')
(root / 'src/styles/fonts.css').write_text('\n\n'.join(css) + '\n')
print('Verified: disjoint Unicode ranges, Romanian/Russian characters, symbols and all weights.')
